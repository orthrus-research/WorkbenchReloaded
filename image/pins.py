"""Pins for the image and for rental bootstraps: one source (``image/pins.toml``), two consumers.

    python image/pins.py lock                 write image/jdks.lock and image/apt-image.txt for the Dockerfile
    python image/pins.py check                exit 1 if the lock files are stale
    python image/pins.py verify [--fill]      download each pinned file and check its SHA-256
    python image/pins.py bootstrap --jdk 26 [--gpu]   print a rental bootstrap script for those needs
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
PINS = HERE / "pins.toml"


def load(path: Path = PINS) -> dict:
    return tomllib.loads(path.read_text(encoding="utf-8"))


def jdk_lock(pins: dict) -> str:
    lines = ["# generated from image/pins.toml by `python image/pins.py lock`: key sha256 url"]
    for key, item in pins["jdk"].items():
        lines.append(f"{key} {item['sha256']} {item['url']}")
    return "\n".join(lines) + "\n"


def tools_lock(pins: dict) -> str:
    """The optional tools (``[tool.<name>]``): name sha256 url and the folders of the archive whose programs go on
    PATH. The image builds in only those the machine's ``[core.image] tools`` names."""
    lines = ["# generated from image/pins.toml by `python image/pins.py lock`: name sha256 url bin-folders"]
    for name, item in (pins.get("tool") or {}).items():
        lines.append(f"{name} {item['sha256']} {item['url']} {','.join(item.get('bin') or ['bin'])}")
    return "\n".join(lines) + "\n"


def apt_list(pins: dict) -> str:
    return "\n".join(["# generated from image/pins.toml"] + pins["apt"]["image"]) + "\n"


def outputs(pins: dict) -> dict[Path, str]:
    return {HERE / "jdks.lock": jdk_lock(pins), HERE / "apt-image.txt": apt_list(pins),
            HERE / "tools.lock": tools_lock(pins)}


def bootstrap(pins: dict, jdks: list[str], gpu: bool) -> str:
    """A rental's bootstrap (D21): stock Ubuntu, only what the bundle needs, every download checked."""
    packages = list(pins["apt"]["rental_base"]) + (list(pins["apt"]["rental_gpu"]) if gpu else [])
    lines = [
        "#!/bin/bash",
        "# Generated by Workbench from image/pins.toml: installs only what this bundle needs. Idempotent.",
        "set -euo pipefail",
        'log() { echo "BOOT $*"; }',
        "export DEBIAN_FRONTEND=noninteractive",
        'log "packages"',
        "apt-get update -qq && apt-get install -y -qq --no-install-recommends ca-certificates >/dev/null",
        f"echo 'APT::Snapshot \"{pins['base']['apt_snapshot']}\";' > /etc/apt/apt.conf.d/50wb-snapshot",
        "apt-get update -qq",
        "apt-get install -y -qq --no-install-recommends " + " ".join(packages) + " >/dev/null",
    ]
    for key in jdks:
        item = pins["jdk"][key]
        lines += [
            f"if [ ! -x /opt/jdk/{key}/bin/java ]; then",
            f'  log "jdk {key}"',
            f"  wget -q -O /tmp/jdk-{key}.tar.gz '{item['url']}'",
            f"  echo '{item['sha256']}  /tmp/jdk-{key}.tar.gz' | sha256sum -c - >/dev/null",
            f"  mkdir -p /opt/jdk/{key} && tar -xzf /tmp/jdk-{key}.tar.gz -C /opt/jdk/{key} --strip-components=1",
            f"  rm /tmp/jdk-{key}.tar.gz",
            "fi",
        ]
    if gpu:
        vgl = pins["virtualgl"]
        check = f"  echo '{vgl['sha256']}  /tmp/vgl.deb' | sha256sum -c - >/dev/null\n" if vgl.get("sha256") else ""
        lines += [
            "if [ ! -x /opt/VirtualGL/bin/vglrun ]; then",
            '  log "virtualgl"',
            f"  wget -q -O /tmp/vgl.deb '{vgl['url']}'",
            check.rstrip("\n"),
            "  apt-get install -y -qq /tmp/vgl.deb >/dev/null && rm /tmp/vgl.deb",
            "fi",
        ]
    java = f"$(/opt/jdk/{jdks[0]}/bin/java -version 2>&1 | head -1)" if jdks else "no jdk"
    lines.append(f'log "ready: $(python3 --version), {java}, vglrun $(test -x /opt/VirtualGL/bin/vglrun && echo yes || echo no)"')
    return "\n".join(line for line in lines if line != "") + "\n"


def sha256_url(url: str) -> str:
    digest = hashlib.sha256()
    with urllib.request.urlopen(url, timeout=600) as response:
        for block in iter(lambda: response.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("lock")
    sub.add_parser("check")
    verify = sub.add_parser("verify")
    verify.add_argument("--fill", action="store_true")
    boot = sub.add_parser("bootstrap")
    boot.add_argument("--jdk", action="append", default=[])
    boot.add_argument("--gpu", action="store_true")
    args = parser.parse_args(argv)
    pins = load()
    if args.action == "lock":
        for path, text in outputs(pins).items():
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.name}")
        return 0
    if args.action == "check":
        stale = [p.name for p, t in outputs(pins).items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale: " + ", ".join(stale) + " (run `python image/pins.py lock`)")
            return 1
        print("locks match pins.toml")
        return 0
    if args.action == "verify":
        failed = 0
        for key, item in (list(pins["jdk"].items()) + [("virtualgl", pins["virtualgl"])]
                          + [(f"tool {name}", item) for name, item in (pins.get("tool") or {}).items()]):
            actual = sha256_url(item["url"])
            if item.get("sha256") and actual != item["sha256"]:
                print(f"MISMATCH {key}: pinned {item['sha256']}, got {actual}")
                failed += 1
            else:
                print(f"{'ok' if item.get('sha256') else 'unpinned'} {key} {actual}")
        return 1 if failed else 0
    print(bootstrap(pins, args.jdk, args.gpu), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
